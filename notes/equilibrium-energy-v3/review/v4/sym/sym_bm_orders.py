"""Second-order Bogoliubov frequency shift from the RETAINED quadratic ODE.

Shows that an O(a**2) frequency correction is generated by c2 and c_d alone,
without a cubic term in tau. Symbolic only.
"""
import sympy as sp

w, a, eta0, eta1, g = sp.symbols("omega a eta_0 eta_1 gamma_s", real=True)
psi = sp.symbols("psi", real=True)
c0, c2, cd = sp.symbols("c_0 c_2 c_d", real=True)

# u1 from the note
# c2 + cd w**2 = -w**2 eta1/eta0
# U0 = c0/w**2 - eta1 a**2/(2 eta0)
# U2 = a**2/6 (eta1/eta0 - 2/g**2)
U0 = c0 / w**2 - eta1 * a**2 / (2 * eta0)
U2 = a**2 / 6 * (eta1 / eta0 - 2 / g**2)
u1 = U0 + U2 * sp.cos(2 * psi)

# Leading delta0 = a cos psi, d0_dot_angle = -a w sin  (time deriv = w * d/dpsi since B1=A1=0)
# At order eps**2 the forcing f2 comes from:
#   c2 * (2 delta0 u1) + cd * (2 d0_dot * v1)   plus products of A,B which vanish
#   and the transport of u1 by the already-known solution.
# Standard: substitute delta = a cos + eps u1 into RHS and into LHS,
# with psi_dot = w + eps**2 B2, a_dot = 0.
#
# LHS secular coefficient at cos psi determines B2.
# We compute it by harmonic balance on the expanded equation.

B2 = sp.symbols("B2")
# delta = a cos psi + u1   (eps=1, but u1 is already O(a**2))
# Treat u1, U0, U2 as O(a**2). Keep terms that produce cos psi at O(a**3)
# (frequency shift O(a**2) multiplies a cos, so O(a**3) in the equation).
delta = a * sp.cos(psi) + u1
# time derivatives with psi_dot = w + B2, B2 = O(a**2), a constant.
# d/dt = (w+B2) d/dpsi
# ddelta/dt = (w+B2) * ddelta/dpsi
# d2 = (w+B2)**2 * d2psi
dpsi = sp.diff(delta, psi)
d2psi = sp.diff(dpsi, psi)
ddt = (w + B2) * dpsi
d2t = (w + B2) ** 2 * d2psi

# RHS = c0 + c2 delta**2 + cd (ddt)**2
# Use the note's c2, cd
c2_v = -w**2 / eta0 * (eta1 - eta0 / g**2)
cd_v = -1 / g**2
rhs = c0 + c2_v * delta**2 + cd_v * ddt**2
lhs = d2t + w**2 * delta
eq = sp.expand(lhs - rhs)

# B2 is O(a**2). Expand eq through order a**3, treating
# U0, U2 ~ a**2, B2 ~ a**2, and drop a**4 and B2**2, B2*U.
# Implement by scaling a -> eps*a, B2 -> eps**2 * B2, and U's already contain a**2.
eps = sp.symbols("eps")
# c0 is the same order as a**2 (Lambda or the constant piece of the quadratic balance)
eq_s = eq.subs({a: eps * a, B2: eps**2 * B2, c0: eps**2 * c0})
eq_s = sp.series(eq_s, eps, 0, 4).removeO()
eq_s = sp.expand(eq_s.subs(eps, 1))

# coefficient of cos psi. Use Fourier.
cos_coeff = sp.simplify(sp.integrate(eq_s * sp.cos(psi), (psi, 0, 2 * sp.pi)) / sp.pi)
sin_coeff = sp.simplify(sp.integrate(eq_s * sp.sin(psi), (psi, 0, 2 * sp.pi)) / sp.pi)
print("sin secular:", sin_coeff)
# cos secular must vanish
# It is linear in B2
B2_sol = sp.solve(sp.Eq(cos_coeff, 0), B2)[0]
B2_sol = sp.simplify(sp.expand(B2_sol))
print("B2 =", B2_sol)
rel = sp.simplify(sp.expand(B2_sol / w))
print("B2/omega =", rel)
# show it is O(a**2) and depends on eta1, gamma, c0
print("collected:", sp.collect(sp.expand(rel), [a**2, c0]))

# Zero-amplitude tune, linear in Lambda. Two truncations.
# delta_eq = -Lambda/eta0. Full system before dropping Lambda*delta/gamma**2:
#   omega_eff**2 / omega**2 = (1 + 2*eta1*delta_eq/eta0) * (1 - delta_eq/gamma**2)
# Retained ODE (eq:ode-L), cd does not move the equilibrium:
#   omega_eff**2 = omega**2 - 2*c2*delta0, c2 = -(omega**2/eta0)*(eta1 - eta0/gamma**2)
Lam = sp.symbols("Lambda", real=True)
de = -Lam / eta0
full = sp.series((1 + 2 * eta1 * de / eta0) * (1 - de / g**2), Lam, 0, 2).removeO()
# Delta omega/omega = half of Delta(omega**2)/omega**2
full_rel = sp.simplify(sp.expand((full - 1) / 2))
c2v = -(w**2 / eta0) * (eta1 - eta0 / g**2)
# omega_eff**2 = w**2 - 2*c2*delta0, delta0 = de
ode_ratio = sp.series((w**2 - 2 * c2v * de) / w**2, Lam, 0, 2).removeO()
ode_rel = sp.simplify(sp.expand((ode_ratio - 1) / 2))
print("full-system Delta omega/omega:", full_rel)
print("retained-ODE Delta omega/omega:", ode_rel)
print("difference (ODE - full):", sp.simplify(ode_rel - full_rel))
